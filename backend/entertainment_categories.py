# Group categories by parent category for organized display
def get_categories_by_group():
    """Return categories organized by parent category"""
    groups = {}
    for cat in ENTERTAINMENT_CATEGORIES:
        category = cat['category']
        if category not in groups:
            groups[category] = []
        groups[category].append(cat)
    return groups

# Get all category IDs for filtering
def get_all_category_ids():
    """Return list of all category IDs"""
    return [cat['id'] for cat in ENTERTAINMENT_CATEGORIES]
